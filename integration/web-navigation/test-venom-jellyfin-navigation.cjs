const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx={URLSearchParams};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname+'/venom-jellyfin-navigation.js','utf8'),ctx);
const p=ctx.VenomNavigationPolicy,u='e8b8de94cf1d443687f6297395efe4ae';
assert.equal(p.channelCardName('9328 TSN 1 FHD','TSN 1 FHD'),'TSN 1 FHD');
assert.equal(p.channelCardName('600 24 NEWS HD','24 NEWS HD'),'24 NEWS HD');
assert.equal(p.channelCardName('24 NEWS HD','24 NEWS HD'),'24 NEWS HD');
assert.equal(p.channelCardName('9328 TSN 1 FHD',null),'9328 TSN 1 FHD');
assert.equal(p.channelCardName('9328 TSN 1 FHD','TSN 2 FHD'),'9328 TSN 1 FHD');
assert.equal(p.channelDisplayName('9328 CA TSN1 FHD'),'TSN1 FHD');
assert.equal(p.channelDisplayName('5849 VIP UK: SKY SPORTS 1 4K'),'SKY SPORTS 1 4K');
assert.equal(p.channelDisplayName('8482 NW : ALJAZEERA  4K'),'ALJAZEERA 4K');
for(const name of ['24 NEWS HD','MBC 1 HD','BBC UK NEWS','360 العربية','TSN 2 FHD'])assert.equal(p.channelDisplayName(name),name);
assert.equal(p.scope('#/livetv','other'),null);
assert.equal(p.scope('#/livetv','620a6c4665b24fb992e9202777b92c19').kind,'live');
assert.equal(p.scope('#/livetv',null),null);
assert.equal(p.scope('#/movies?topParentId=normal',u),null);
assert.equal(p.scope('#/livetv?tab=2',u).kind,'live');
assert.equal(p.scope('#/movies?topParentId=8bc59dd4449848da1641f0bd0eba752c',u).kind,'Movie');
assert(p.hiddenLabels('Movie',false).includes('Genres'));
assert(!p.hiddenLabels('Movie',true).includes('Genres'));
assert(!p.hiddenLabels('live',false).includes('Channels'));
assert(p.hiddenLabels('live',false).includes('Recordings'));
const fav=new URLSearchParams(p.favouritesUrl('Series','server').split('?')[1]);
assert.equal(fav.get('IsFavorite'),'true');assert.equal(fav.get('type'),'Series');assert.equal(fav.get('tag'),'Venom TV');
const category=new URLSearchParams(p.categoryUrl('genre','library','Series','server').split('?')[1]);
assert.equal(category.get('genreId'),'genre');assert.equal(category.get('parentId'),'library');assert.equal(category.get('id'),null);
console.log('PASS: account/library scoping, live navigation and category readiness');
